"""MCP OAuth install routes for the OpenHands App Server.

Hosted counterpart of the agent-server's ``/api/mcp/oauth/*`` flow. There, a
FastMCP OAuth client waits for the provider to redirect the browser to a
loopback callback server (``http://localhost:<port>/callback``), which only
works when the browser and the agent-server share a machine. Here the app
server runs the same SDK probe (``_probe_mcp_server``) with an OAuth client
whose redirect URI is the public ``GET /api/v1/mcp/oauth/callback`` route, so
the provider sends the user's popup back to the app server.

Flow
----
1. ``POST /api/v1/mcp/oauth/start`` validates the candidate server exactly like
   ``POST /api/v1/mcp/test`` (redacted-secret restore, remote transports only,
   SSRF guard), creates a job and runs the probe in a worker thread. The
   probe's OAuth client publishes the provider's authorization URL and the
   route returns it with the job id.
2. The browser opens the authorization URL. After consent the provider
   redirects to ``GET /api/v1/mcp/oauth/callback?code=...&state=...``, which
   stores the code on the job (found through the single-use ``state``) and
   renders a small "you can close this window" page.
3. The worker thread picks the code up, finishes the token exchange and
   ``tools/list``, and stores the result. ``GET /api/v1/mcp/oauth/status/{job_id}``
   reports progress and, on success, the OAuth state the client persists in
   settings (``mcp_config[name].auth.state``) - the agent-server contract.

Jobs live in Redis so the callback and the status polls may land on any app
server replica; only the probe thread is pinned to the pod that started it.
The stored result carries OAuth tokens and is encrypted at rest with the app
server's ``JwtService``. The SDK bounds the whole probe, including the wait for
the user's consent, by the request ``timeout`` (at most 120 seconds), so
clients send the maximum for OAuth installs.
"""

